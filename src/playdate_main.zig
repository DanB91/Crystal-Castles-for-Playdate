        0,
        background_width,
        background_height,
        pdapi.solid_color_to_color(pdapi.LCDSolidColor.ColorWhite),
    );
    var y: pdapi.Pixel = 0;
    for (lines.items()) |line| {
        _ = pdapi.draw_text(line.bytes, 0, y);
        y += pdapi.get_font_height();
    }
}

