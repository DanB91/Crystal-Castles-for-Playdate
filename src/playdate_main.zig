fn draw_character(
    char: isize,
    position: cc.V2,
    color: cc.Color,
    castle_bitmap_data: pdapi.BitmapData,
    castle_priority_mask: []u8,
) void {
    //    TRAI 000 HW.AY    ; y auto dec
    //     TRAI 0FF HW.YIN

    //     TRAM AL.X XB
    //     LDY AL.DIG
    //     CPY #4A
    //     IFMI
    //      TR16AI AL.55D AL.PTR
    //      TYA
    //      SUB #40
    //     ELSE
    //      TR16AI AL.55L AL.PTR
    //      TYA
    //      SUB #4A
    //     ENDIF

    const bitmap_index_start: usize = @intCast(char * cc.CHARACTER_BITMAP_WIDTH);
    const bitmap_set = cc.CHARACTER_BITMAPS;

    //     JSR AL.5OT

    // AL.5OT:
    {
        var position_cursor = position;
        //     STA TEMP1    ;  mult by 5 so (A) points to sym
        //     ASLS 2
        //     ADD TEMP1
        //     STA TEMP1

        //     TRAI 5 AL.TMP
        //     LDX AL.COL
        // 10$:
        var i: usize = 0;
        for (0..cc.CHARACTER_BITMAP_WIDTH) |x| {
            //     LDY TEMP1
            //     TRAM AL.Y YB
            position_cursor[1] = position[1];
            const bitmap_index = bitmap_index_start + x;
            //     LDA @AL.PTR(Y)
            var character_row = bitmap_set[bitmap_index];
            //     LDY #0F
            //     .REPT 5
            for (0..cc.CHARACTER_BITMAP_HEIGHT) |_| {
                //     ASL
                //     IFCS
                if (character_row & 0x80 != 0) {
                    //     STX VB
                    draw_color(
                        position_cursor,
                        color,
                        i,
                        castle_bitmap_data,
                        castle_priority_mask,
                    );
                    i += 1;
                    //     ENDIF
                }
                //NOTE: this code just causes auto increment
                //     IFCC
                //     LDY VB
                //      ENDIF

                // ;    DEC YB
                position_cursor -= .{ 0, 1 };
                //     .ENDM

                character_row <<= 1;
            }

            //     INC XB
            position_cursor += .{ 1, 0 };
            //     INC TEMP1
            //     DEC AL.TMP
            //     BNE 10$
        }
    }
    // 8$:
    //     TRAI 0FF HW.AY    ; auto dec off
}

fn screen_erase(
    start_position: cc.V2,
    number_of_pixel_columns_to_erase: isize,
    castle_bitmap_data: pdapi.BitmapData,
    castle_priority_mask: []u8,
) void {
    //  STA TEMP1
    var column_cursor = number_of_pixel_columns_to_erase;
    //     LDA AL.X
    //     STA XB
    //     LDA AL.Y
    //     STA YB
    //     INC YB
    var position = start_position + cc.V2{ 0, 1 };

    //     TRAI 000 HW.AY    ; auto dec y
    //     TRAI 0FF HW.YIN

    //     LDA #00F
    //     INC TEMP1
    // 10$:
    //     DEC TEMP1
    //     BEQ 20$
    while (column_cursor > 0) {
        //     STA VB
        //     .REPT 7
        for (0..8) |_| {
            // ;    DEC YB
            //     STA VB
            //     .ENDM

            //NOTE: screen erase is always black
            draw_color(
                position,
                .{
                    .value = .Black,
                    .high_priority = false,
                },
                0,
                castle_bitmap_data,
                castle_priority_mask,
            );

            position[1] -= 1;
        }
        //     INC XB
        position[0] += 1;
        //     LDY AL.Y
        //     STY YB
        //     INC YB
        position[1] = start_position[1] + 1;

        column_cursor -= 1;
        //     JMP 10$
    }
    // 20$:
    //     TRAI 0FF HW.AY
}
fn draw_color(
    position: cc.V2,
    color: cc.Color,
    pixel_number: usize,
    castle_bitmap_data: pdapi.BitmapData,
    castle_priority_mask: []u8,
) void {
    const is_white_pixel = switch (color.value) {
        .White => true,
        .Black => false,
        .Gray => gray_modulo(pixel_number),
        .DarkGray => dark_gray_modulo(pixel_number),
        .Red => red_modulo(pixel_number),
        //TODO add yellow modulo
        .Yellow => unreachable,
    };
    draw_pixel(
        position,
        is_white_pixel,
        color.high_priority,
        castle_bitmap_data,
        castle_priority_mask,
    );
}

fn draw_pixel(
    position: cc.V2,
    is_white: bool,
    high_priority: bool,
    castle_bitmap_data: pdapi.BitmapData,
    castle_priority_mask: []u8,
) void {
    toolbox.assert(bounds_check(position), "Drawing pixel out of bounds!", .{});
    const dy = position[1];
    const dx_byte = @divTrunc(position[0], 8);
    const dx_bit = @mod(position[0], 8);
    const bitmap_index: usize = @intCast(dy * castle_bitmap_data.row_bytes + dx_byte);
    if (is_white) {
        castle_bitmap_data.data[bitmap_index] |= @as(u8, 0x80) >> @intCast(dx_bit);
    } else {
        castle_bitmap_data.data[bitmap_index] &= ~(@as(u8, 0x80) >> @intCast(dx_bit));
    }
    castle_bitmap_data.mask.?[bitmap_index] |= @as(u8, 0x80) >> @intCast(dx_bit);

    if (high_priority) {
        castle_priority_mask[bitmap_index] |= @as(u8, 0x80) >> @intCast(dx_bit);
    } else {
        castle_priority_mask[bitmap_index] &= ~(@as(u8, 0x80) >> @intCast(dx_bit));
    }
}
inline fn clear_pixel(
    position: cc.V2,
    castle_bitmap_data: pdapi.BitmapData,
) void {
    toolbox.assert(bounds_check(position), "Drawing pixel out of bounds!", .{});
    const dy = position[1];
    const dx_byte = @divTrunc(position[0], 8);
    const dx_bit = @mod(position[0], 8);
    const bitmap_index: usize = @intCast(dy * castle_bitmap_data.row_bytes + dx_byte);
    castle_bitmap_data.mask.?[bitmap_index] &= ~(@as(u8, 0x80) >> @intCast(dx_bit));
}

//TODO remove.  we should not be bounds checking per pixel
fn bounds_check(position: cc.V2) bool {
    return position[0] >= 0 and position[0] < cc.SCREEN_WIDTH and
        position[1] >= 0 and position[1] < cc.SCREEN_HEIGHT;
}
