pub export fn eventHandler(playdate: *pdapi.PlaydateAPI, event: pdapi.PDSystemEvent, arg: u32) callconv(.c) c_int {
    _ = arg;
    switch (event) {
        .EventInit => {
            pdapi.set_playdate_api(playdate);
            toolbox.init_playdate_runtime(
                playdate.system.realloc,
                playdate.system.logToConsole,
                playdate.system.@"error",
                playdate.system.getElapsedTime,
                playdate.system.getCurrentTimeMilliseconds,
            );
            pdapi.set_refresh_rate(50);

            const frame_arena = toolbox.Arena.init(toolbox.kb(512));
            const global_arena = toolbox.Arena.init(toolbox.mb(2));

            const background_image = pdapi.load_bitmap("assets/images/background");
            const color_motion_object_tiles = pdapi.load_bitmap_table("assets/images/color_motion_objects");
            const dithered_motion_object_tiles = pdapi.load_bitmap_table("assets/images/dithered_motion_objects");
            const castle_bitmap = pdapi.new_bitmap_solid_color(
                cc.SCREEN_WIDTH,
                cc.SCREEN_HEIGHT,
                .ColorClear,
            );
            const castle_priority_mask = global_arena.push_slice_clear(
                u8,
                cc.SCREEN_HEIGHT * (cc.SCREEN_WIDTH / 8),
            );
            var masks: [TOTAL_TILES]?[]const u8 = undefined;
            for (&masks, 0..) |*dest_ptr, i| {
                const tile = pdapi.get_table_bitmap(
                    color_motion_object_tiles,
                    @intCast(i),
                ).?;
                const data = pdapi.get_bitmap_data(tile);
                if (data.mask) |src| {
                    const dest = global_arena.push_slice(u8, src.len);
                    @memcpy(dest, src);
                    dest_ptr.* = dest;
                } else {
                    dest_ptr.* = null;
                }
            }

            const font = pdapi.load_font("/System/Fonts/Roobert-10-Bold.pft");
            pdapi.set_font(font);

            const StaticVars = struct {
                var platform_state: PlatformState = undefined;
            };
            const game_state = global_arena.push(cc.GameState);
            StaticVars.platform_state = .{
                .background_image = background_image,
                .dithered_motion_object_tiles = dithered_motion_object_tiles,
                .color_motion_object_tiles = color_motion_object_tiles,
                .frame_arena = frame_arena,
                .global_arena = global_arena,
                .game_state = game_state,
                .last_frame_time = toolbox.now(),
                .castle_bitmap = castle_bitmap,
                .castle_priority_mask = castle_priority_mask,
                .frame_count = 0,
                .motion_object_masks = masks,
            };

            cc.init(
                StaticVars.platform_state.game_state,
                StaticVars.platform_state.global_arena,
            );
            fiber.init(global_arena, 2, toolbox.kb(64));
            fiber.go(cc.update, .{StaticVars.platform_state.game_state}, global_arena);

            pdapi.set_update_callback(update_and_render, &StaticVars.platform_state);
        },
        else => {},
    }
    return 0;
}

fn update_and_render(userdata: ?*anyopaque) callconv(.c) c_int {
    profiler.start_profiler();
    const platform_state: *PlatformState = @ptrCast(@alignCast(userdata.?));
    const game_state = platform_state.game_state;
    defer {
        platform_state.frame_arena.reset();
        platform_state.frame_count +%= 1;
    }

    const now = toolbox.now();
    const dt = now.subtract(platform_state.last_frame_time);
    platform_state.last_frame_time = now;

    {
        const is_running = pdapi.is_button_down(pdapi.BUTTON_B);
        const delta: isize = if (is_running) 5 else 2;
        profiler.begin("cc.update");
        game_state.input_dt = dt;
        game_state.input_button_pressed = pdapi.is_button_pressed(pdapi.BUTTON_A);
        if (pdapi.is_button_down(pdapi.BUTTON_RIGHT)) {
            game_state.input_trackball_position[0] += delta;
        }
        if (pdapi.is_button_down(pdapi.BUTTON_LEFT)) {
            game_state.input_trackball_position[0] -= delta;
        }
        if (pdapi.is_button_down(pdapi.BUTTON_UP)) {
            game_state.input_trackball_position[1] += delta;
        }
        if (pdapi.is_button_down(pdapi.BUTTON_DOWN)) {
            game_state.input_trackball_position[1] -= delta;
        }
        fiber.yield();
        profiler.end();
    }
    const command_count: usize = if (game_state.output_draw_command_queue.rcursor <=
        game_state.output_draw_command_queue.wcursor)
        game_state.output_draw_command_queue.wcursor -
            game_state.output_draw_command_queue.rcursor
    else
        (game_state.output_draw_command_queue.data.len -
            game_state.output_draw_command_queue.rcursor) +
            game_state.output_draw_command_queue.wcursor + 1;
    {
        profiler.begin("update_castle_bitmap");
        update_castle_bitmap(platform_state);
        profiler.end();
    }

    if (pdapi.is_button_pressed(pdapi.BUTTON_B)) {
        game_state.input_credits = @min(game_state.input_credits + 1, 99);
    }
    const background_image = platform_state.background_image;

    pdapi.clear_screen(pdapi.LCDSolidColor.ColorWhite);

    //draw game
    {
        profiler.begin("draw game");
        defer profiler.end();

        const game_offset_x =
            (pdapi.LCD_COLUMNS - cc.SCREEN_WIDTH) / 2;
        const game_offset_y =
            (pdapi.LCD_ROWS - cc.SCREEN_HEIGHT) / 2;
        pdapi.set_draw_offset(game_offset_x, game_offset_y);
        defer pdapi.set_draw_offset(0, 0);

        pdapi.fill_rect(0, 0, cc.SCREEN_WIDTH, cc.SCREEN_HEIGHT, pdapi.solid_color_to_color(.ColorBlack));

        {
            pdapi.set_clip_rect(
                0,
                0,
                cc.SCREEN_WIDTH,
                @intCast(game_state.background_clip_y),
            );
            defer pdapi.clear_clip_rect();
            pdapi.draw_bitmap(
                background_image,
                0,
                0,
                .BitmapUnflipped,
            );
        }
        pdapi.draw_bitmap(platform_state.castle_bitmap, 0, 0, .BitmapUnflipped);

        //draw sprites, aka motion objects
        {
            //NOTE: Dithered tiles look better on the explaination board, but the color tiles
            //      look better during game play
            const tiles = if (game_state.current_state == .ExplainationBoard)
                platform_state.dithered_motion_object_tiles
            else
                platform_state.color_motion_object_tiles;
            for (game_state.output_motion_objects) |mo| {
                const tile = pdapi.get_table_bitmap(
                    tiles,
                    @intCast(mo.picture_number),
                ).?;
                const x: pdapi.Pixel = @intCast(mo.position[0] & 0xFF);
                const y: pdapi.Pixel = @intCast(256 - 16 - (mo.position[1] & 0xFF) - cc.Y_COORDINATE_OFFSET);

                const mo_data = pdapi.get_bitmap_data(tile);
                const mo_mask = mo_data.mask orelse
                    //TODO: figure out if this can ever be null
                    unreachable;
                const default_mo_mask =
                    platform_state.motion_object_masks[@intCast(mo.picture_number)] orelse
                    //TODO: figure out if this can ever be null
                    unreachable;
                @memcpy(mo_mask, default_mo_mask);
                if (mo.low_priority) {
                    blend_low_priority_motion_object(
                        x,
                        y,
                        mo_data,
                        &RED_MASKS[@intCast(mo.picture_number)],
                        platform_state.castle_priority_mask,
                    );
                }
                pdapi.draw_bitmap(tile, x, y, .BitmapUnflipped);
            }
        }
    }
    //draw hud
    {
        const build_number_str =
            toolbox.str8fmt("{}{s}", .{
                build_info.BUILD_NUMBER,
                if (toolbox.IS_DEBUG) "D" else "R",
            }, platform_state.frame_arena);
        const text_width = pdapi.get_text_width(build_number_str.bytes);
        const x = pdapi.LCD_COLUMNS - text_width - 1;
        const y = pdapi.LCD_ROWS - pdapi.get_font_height() - 1;
        _ = pdapi.draw_text(build_number_str.bytes, x, y);
    }

    profiler.end_profiler();
    if (false) { //pdapi.is_button_down(pdapi.BUTTON_B)) {
        draw_debug_and_profiler_hud(platform_state, command_count);
    }
    //draw fps
    {
        pdapi.draw_fps(pdapi.LCD_COLUMNS - 20, 0);
    }

    return 1;
}

pub fn update_castle_bitmap(
    platform_state: *PlatformState,
) void {
    const castle_bitmap_data = pdapi.get_bitmap_data(platform_state.castle_bitmap);

    const game_state = platform_state.game_state;
    while (game_state.output_draw_command_queue.dequeue_one(.AsMuchAsYouCan)) |command| {
        const StaticVars = struct {
            var line_number: isize = 0;
        };
        StaticVars.line_number += 1;
        switch (command.shape) {
            .Line1 => draw_line1(
                command.number_of_segments,
                command.position,
                command.color,
                castle_bitmap_data,
                platform_state.castle_priority_mask,
            ),
            .Line2 => draw_line2(
                command.number_of_segments,
                command.position,
                command.color,
                castle_bitmap_data,
                platform_state.castle_priority_mask,
            ),
            .Line3 => draw_line3(
                command.number_of_segments,
                command.position,
                command.color,
                castle_bitmap_data,
                platform_state.castle_priority_mask,
            ),
            .Character => draw_character(
                command.character,
                command.position,
                command.color,
                castle_bitmap_data,
                platform_state.castle_priority_mask,
            ),
            .ScreenErase => screen_erase(
                command.position,
                command.number_of_segments,
                castle_bitmap_data,
                platform_state.castle_priority_mask,
            ),
            .Pixel => {
                draw_color(
                    command.position,
                    command.color,
                    0,
                    castle_bitmap_data,
                    platform_state.castle_priority_mask,
                );
            },
            .ClearEntireScreen => {
                game_state.background_clip_y = 0;
                @memset(castle_bitmap_data.mask.?, 0);
            },
            .None => unreachable,
        }
    }
}
fn blend_low_priority_motion_object(
    dest_x: pdapi.Pixel,
    dest_y: pdapi.Pixel,
    mo_data: pdapi.BitmapData,
    red_mask: []const u8,
    castle_priority_mask: []const u8,
) void {
    //We have made the assumption that tiles are 8x16.  This will break if this ever changes
    const TILE_HEIGHT = 16;
    //TODO put in init?
    toolbox.asserteq(
        1,
        mo_data.row_bytes,
        "Unexpected motion object mask byte width",
    );
    for (0..TILE_HEIGHT) |y| {
        const ieff_y = @as(pdapi.Pixel, @intCast(y)) + dest_y;
        if (ieff_y < 0) {
            continue;
        }
        const eff_y: usize = @intCast(ieff_y);
        const eff_x: usize = @intCast(dest_x);
        //TODO: this is definitely off.... probably in the x dimension
        //Move to bad spot and then set a breakpoint and skip ahead to the affected sprite
        const mask_byte_start = eff_y * (cc.SCREEN_WIDTH / 8) + (eff_x / 8);

        const bit_x = eff_x % 8;
        const left_shift: u3 = @intCast(bit_x);
        var castle_mask: u8 = castle_priority_mask[mask_byte_start] << left_shift;
        if (bit_x != 0) {
            const right_shift: u3 = @intCast(8 - bit_x);
            castle_mask |=
                castle_priority_mask[mask_byte_start + 1] >> right_shift;
        }
        castle_mask = ~castle_mask;

        const mo_mask = &mo_data.mask.?[y];
        //TODO red color flags
        mo_mask.* &= castle_mask | red_mask[y];
    }
}
